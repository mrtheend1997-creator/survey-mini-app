export const dict: Record<Lang, Record<Key, string>> = { uz, oz, ru }

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let s = dict[lang][key] ?? dict.uz[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
  return s
}

/**
 * The text of a translated DB field in `lang`, e.g. pick(survey, 'title', lang).
 * A missing translation is never made up: the next language in FALLBACK is shown instead.
 */
export function pick(obj: object | null | undefined, field: string, lang: Lang): string {
  if (!obj) return ''
  const o = obj as Record<string, unknown>
  for (const l of FALLBACK[lang]) {
    const v = o[`${field}_${l}`]
    if (typeof v === 'string' && v.trim()) return v
  }
  return ''
}

/** True when the field has some text, but none in `lang` (the respondent sees a fallback). */
export function isFallback(obj: object | null | undefined, field: string, lang: Lang): boolean {
  if (!obj) return false
  const o = obj as Record<string, unknown>
  const has = (l: Lang) => typeof o[`${field}_${l}`] === 'string' && (o[`${field}_${l}`] as string).trim() !== ''
  return !has(lang) && LANGS.some(has)
}

/** Languages in which a field that has some text is still empty. */
export function missingLangs(obj: object | null | undefined, field: string): Lang[] {
  if (!obj) return []
  const o = obj as Record<string, unknown>
  const has = (l: Lang) => typeof o[`${field}_${l}`] === 'string' && (o[`${field}_${l}`] as string).trim() !== ''
  return LANGS.some(has) ? LANGS.filter((l) => !has(l)) : []
}

