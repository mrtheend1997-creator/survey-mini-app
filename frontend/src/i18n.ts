export const dict: Record<Lang, Record<Key, string>> = { uz, ru }

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let s = dict[lang][key] ?? dict.uz[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
  return s
}

/** Pick the uz/ru variant of a bilingual DB field, e.g. pick(survey, 'title', lang). */
export function pick(obj: object | null | undefined, field: string, lang: Lang): string {
  if (!obj) return ''
  const o = obj as Record<string, unknown>
  const v = o[`${field}_${lang}`] as string | undefined
  return v || (o[`${field}_${lang === 'uz' ? 'ru' : 'uz'}`] as string) || ''
}

